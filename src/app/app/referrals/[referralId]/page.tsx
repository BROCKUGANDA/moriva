import { redirect, notFound } from "next/navigation";
import Link from "next/link";
import { getSessionUser } from "@/domains/identity/service";
import { db } from "@/lib/db";
import { SectionHeading, StatusBadge, SimulationBanner, InlineNotice } from "@/components/moriva/status";
import { ReferralTimelineActions } from "@/components/moriva/referral-timeline-actions";

export const metadata = { title: "Referral" };
export const dynamic = "force-dynamic";

export default async function ReferralDetailPage({ params }: { params: Promise<{ referralId: string }> }) {
  const { referralId } = await params;
  const user = await getSessionUser();
  if (!user) redirect("/login");
  const r = await db.referral.findUnique({
    where: { id: referralId },
    include: { providerService: { include: { provider: true } }, events: { orderBy: { occurredAt: "asc" } }, consentEvent: true },
  }).catch(() => null);
  if (!r || r.userId !== user.id) notFound();

  return (
    <div className="mx-auto max-w-3xl">
      <Link href="/app/referrals" className="text-sm text-moriva-slate underline-offset-4 hover:underline">← All referrals</Link>
      <SectionHeading title={r.providerService.serviceName} level={1} />
      <p className="text-sm text-moriva-slate">{r.providerService.provider.displayName} · {r.providerService.location}</p>
      <div className="mt-2 flex flex-wrap items-center gap-2">
        <StatusBadge tone="teal">{r.state.replace(/_/g, " ").toLowerCase()}</StatusBadge>
        {r.providerService.provider.demoData && <StatusBadge tone="coral">SIMULATED PROVIDER</StatusBadge>}
      </div>
      {r.providerService.provider.demoData && <div className="mt-3"><SimulationBanner /></div>}

      <section className="mt-5 rounded-2xl border border-moriva-line bg-white p-6 shadow-card" aria-labelledby="shared">
        <h2 id="shared" className="font-display text-lg font-bold text-moriva-ink">What was shared</h2>
        <ul className="mt-2 flex flex-wrap gap-2">
          {r.sharedFields.split("|").filter(Boolean).map((f) => (
            <li key={f} className="rounded-full bg-muted px-3 py-1 text-xs font-semibold text-moriva-ink">{f.replace(/_/g, " ").toLowerCase()}</li>
          ))}
        </ul>
        {r.consentEvent && (
          <p className="mt-2 text-xs text-moriva-slate">
            Consent: {r.consentEvent.purposeCode} v{r.consentEvent.purposeVersion} · status {r.consentEvent.status.toLowerCase()} ·
            granted {new Date(r.consentEvent.grantedAt).toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short" })}
            {r.consentEvent.expiresAt ? ` · expires ${r.consentEvent.expiresAt.toISOString().slice(0, 10)}` : " · no expiry set"}
          </p>
        )}
        <p className="mt-1 text-xs text-moriva-slate">Withdraw consent from the privacy centre to stop any future sharing.</p>
      </section>

      <section className="mt-5 rounded-2xl border border-moriva-line bg-white p-6 shadow-card" aria-labelledby="timeline">
        <h2 id="timeline" className="font-display text-lg font-bold text-moriva-ink">Timeline</h2>
        <ol className="mt-3 space-y-3" data-testid="referral-timeline">
          {r.events.map((e) => (
            <li key={e.id} className="border-l-2 border-moriva-mist pl-4">
              <p className="text-sm font-semibold text-moriva-ink">
                {e.eventType.replace(/_/g, " ").toLowerCase()}
                {e.toState ? ` → ${e.toState.replace(/_/g, " ").toLowerCase()}` : ""}
              </p>
              <p className="text-xs text-moriva-slate">
                {new Date(e.occurredAt).toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short" })} · actor: {e.actorType.toLowerCase().replace("_", " ")}
                {e.evidenceSource ? <> · evidence: <strong className="text-moriva-ink">{e.evidenceSource.replace(/_/g, " ").toLowerCase()}</strong></> : null}
              </p>
              {e.safeReasonCode && <p className="text-xs text-moriva-slate">Reason category: {e.safeReasonCode.replace(/_/g, " ").toLowerCase()}</p>}
            </li>
          ))}
        </ol>
        <p className="mt-3 text-xs text-moriva-slate">
          Evidence types are kept separate: provider-confirmed events come from the provider side; patient-reported events
          are your own reports; simulated events are generated by this demo.
        </p>
      </section>

      <section className="mt-5">
        <ReferralTimelineActions
          referralId={r.id}
          state={r.state}
          version={r.version}
        />
      </section>
    </div>
  );
}
